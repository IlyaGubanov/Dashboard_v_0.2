test('every playlist and segment rejects copied links and rights revocation without caching', async ({ page, playwright }) => {
  await login(page);
  const all = await catalog(page);
  const camera = all.cameras.find((c: { available: boolean }) => c.available);
  const playlist = '/media/cam-' + camera.id + '/index.m3u8';
  const response = await page.request.get(playlist);
  expect(response.status()).toBe(200);
  expect(response.headers()['cache-control']).toContain('no-store');
  const master = await response.text();
  const child = master.split('\n').find(line => line && !line.startsWith('#'))!;
  const variant = await page.request.get(new URL(child, response.url()).href);
  const lines = (await variant.text()).split('\n');
  const segment = lines.filter(line => line && !line.startsWith('#')).at(-1)!;
  const segmentUrl = new URL(segment, variant.url()).href;
  expect((await page.request.get(segmentUrl)).status()).toBe(200);
  const anonymous = await playwright.request.newContext();
  expect((await anonymous.get(response.url())).status()).toBe(401);
  expect((await anonymous.get(segmentUrl)).status()).toBe(401);
  expect((await anonymous.post(new URL('/api/video/internal/mediamtx-auth', response.url()).href)).status()).toBe(404);
  await anonymous.dispose();
  const viewer = await playwright.request.newContext({ baseURL: response.url().split('/media/')[0] });
  expect((await viewer.post('/api/auth/login', { data: { login: 'video-qa-viewer', password: 'VideoTest2026local' } })).ok()).toBe(true);
  const visible = await (await viewer.get('/api/video/catalog')).json();
  expect(visible.sites).toHaveLength(1);
  const foreign = all.cameras.find((c: { siteId: number; available: boolean }) => c.available && c.siteId !== visible.sites[0].id);
  expect((await viewer.get('/media/cam-' + foreign.id + '/index.m3u8')).status()).toBe(403);
  expect((await viewer.get('/media/cam-' + foreign.id + '/seg1.mp4')).status()).toBe(403);
  const viewerMe = await (await viewer.get('/api/auth/me')).json();
  const userId = viewerMe.id;
  expect((await page.request.put('/api/video/grants/' + userId, { data: { grants: [] } })).ok()).toBe(true);
  expect((await viewer.get(playlist)).status()).toBe(403);
  expect((await viewer.get(segmentUrl)).status()).toBe(403);
  expect((await page.request.put('/api/video/grants/' + userId, { data: { grants: [{ siteId: visible.sites[0].id, manage: false }] } })).ok()).toBe(true);
  expect((await page.request.patch('/api/users/' + userId, { data: { isActive: false } })).ok()).toBe(true);
  expect((await viewer.get(playlist)).status()).toBe(401);
  expect((await page.request.patch('/api/users/' + userId, { data: { isActive: true } })).ok()).toBe(true);
  await viewer.post('/api/auth/logout');
  expect((await viewer.get(segmentUrl)).status()).toBe(401);
  await viewer.dispose();
  await page.goto('/video');
  await expect(page.locator('video')).toHaveCount(4);
  await page.goto('/help');
  await expect(page.locator('video')).toHaveCount(0);
});
