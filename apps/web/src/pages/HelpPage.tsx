export function HelpPage() {
  const { data: me } = useQuery(meQuery);
  const roles = new Set(me?.directions.map((d) => d.role));
  const mine: Role[] = [
    ...(roles.has('EDITOR') ? (['editor'] as const) : []),
    ...(roles.has('CURATOR') ? (['curator'] as const) : []),
    ...(me?.globalRole === 'MANAGEMENT' ? (['management'] as const) : []),
    ...(me?.globalRole === 'ADMIN' ? (['admin'] as const) : []),
  ];
  // своя роль — первой и раскрытой
  const order = [...SECTIONS].sort((a, b) => Number(mine.includes(b.key)) - Number(mine.includes(a.key)));
  return (
    <Stack className="reading-page" maw={900}>
      <div>
        <Title order={2}>Справка</Title>
        <Text c="dimmed" size="sm">
          Коротко о главном. Ваш раздел — первым.
        </Text>
      </div>
      <Accordion multiple variant="separated" defaultValue={[...mine, ...(mine.length ? [] : ['all'])]}>
        {order.map((s) => (
          <Accordion.Item key={s.key} value={s.key}>
            <Accordion.Control>
              <Group gap="sm">
                <Text fw={600}>{s.title}</Text>
                {mine.includes(s.key) && (
                  <Badge size="sm" variant="light">
                    ваша роль
                  </Badge>
                )}
              </Group>
              <Text size="xs" c="dimmed">
                {s.lead}
              </Text>
            </Accordion.Control>
            <Accordion.Panel>
              <Stack gap="md">
                {s.steps.map((st) => (
                  <div key={st.t}>
                    <Text fw={600} size="sm" mb={4}>
                      {st.t}
                    </Text>
                    <List size="sm" spacing={4}>
                      {st.items.map((i) => (
                        <List.Item key={i}>{i}</List.Item>
                      ))}
                    </List>
                  </div>
                ))}
              </Stack>
            </Accordion.Panel>
          </Accordion.Item>
        ))}
      </Accordion>
    </Stack>
  );
}
