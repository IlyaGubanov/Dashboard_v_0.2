async page => {
  const must = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('http://localhost:5173/staffing');
  await page.locator('[role=img] svg').first().waitFor();
  const cards = page.locator('.staffing-stats');
  must((await cards.innerText()).replace(/\s/g, ' ').includes('4 547 ед.'), 'Штат');
  must((await cards.innerText()).replace(/\s/g, ' ').includes('4 539 чел.'), 'Факт');
  must((await cards.innerText()).includes('30/41 сопоставимых'), 'Полнота данных');
  await page.screenshot({ path: 'apps/api/data/staffing-desktop.png', fullPage: true });
  await page.getByRole('tab', { name: 'Подразделения', exact: true }).click();
  const panel = page.getByRole('tabpanel', { name: 'Подразделения', exact: true });
  await page.getByRole('textbox', { name: 'Поиск подразделения', exact: true }).fill('Управление делами');
  await page.waitForURL(/q=/);
  must(await panel.locator('tbody tr').count() === 1, 'Поиск');
  must((await panel.locator('tfoot').innerText()).includes('17'), 'Итог фильтра');
  await page.getByRole('button', { name: 'Сбросить', exact: true }).click();
  await page.getByRole('button', { name: 'Новый срез', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Месяц').fill('2097-11');
  await dialog.getByLabel('Данные на дату').fill('2097-11-15');
  await dialog.getByLabel('Скопировать подразделения и штат').click();
  await page.getByRole('option', { name: '01.07.2026', exact: true }).click();
  await dialog.getByRole('button', { name: 'Сохранить срез', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.waitForURL(/month=2097-11/);
  await panel.getByRole('button', { name: 'Второй отдел', exact: true }).click();
  dialog = page.getByRole('dialog');
  must(await dialog.getByLabel('Факт, чел.').inputValue() === '', 'Скопированный факт должен оставаться пустым');
  await dialog.getByLabel('Факт, чел.').fill('5');
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await panel.getByRole('checkbox', { name: 'Выбрать: Второй отдел', exact: true }).check();
  await page.getByRole('button', { name: 'Архивировать', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Подтвердить', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('textbox', { name: 'Состояние', exact: true }).click();
  await page.getByRole('option', { name: 'Архив строк', exact: true }).click();
  must(await panel.locator('tbody tr').count() === 1, 'Архив строки');
  must((await panel.locator('tfoot').innerText()).includes('5'), 'Итоги архива');
  await panel.getByRole('checkbox', { name: 'Выбрать: Второй отдел', exact: true }).check();
  await page.getByRole('button', { name: 'Восстановить', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Подтвердить', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Сбросить', exact: true }).click();
  await page.getByRole('button', { name: 'Подразделение', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', { name: 'Подразделение', exact: true }).fill('Тестовый отдел QA');
  await dialog.getByLabel('Штат, ед.').fill('2.5');
  await dialog.getByLabel('Факт, чел.').fill('2');
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  must(await panel.getByRole('button', { name: 'Тестовый отдел QA', exact: true }).isVisible(), 'Добавление строки');
  await page.getByRole('tab', { name: 'ФОТ по годам', exact: true }).click();
  must((await page.getByRole('tabpanel', { name: 'ФОТ по годам' }).innerText()).replace(/\s/g, ' ').includes('3 719,7 млн ₽'), 'Итог ФОТ');
  await page.getByRole('button', { name: 'Редактировать ФОТ', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', { name: 'Поиск в редакторе ФОТ' }).fill('Бухгалтерия');
  await dialog.getByRole('button', { name: 'Добавить строку', exact: true }).click();
  must(await dialog.getByRole('textbox', { name: 'Поиск в редакторе ФОТ' }).inputValue() === '', 'Поиск сбрасывается при добавлении');
  await dialog.getByRole('button', { name: 'Отмена', exact: true }).click();
  await page.goto('http://localhost:5173/staffing');
  await page.getByRole('button', { name: 'Сменить тему' }).click();
  await page.locator('html[data-mantine-color-scheme=dark]').waitFor();
  await page.screenshot({ path: 'apps/api/data/staffing-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Сменить тему' }).click();
  await page.setViewportSize({ width: 375, height: 900 });
  await page.waitForFunction(() => document.querySelector('nav').getBoundingClientRect().right <= 0);
  await page.screenshot({ path: 'apps/api/data/staffing-phone.png', fullPage: true });
  must(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Нет горизонтального переполнения телефона');
  await page.setViewportSize({ width: 3440, height: 1440 });
  await page.screenshot({ path: 'apps/api/data/staffing-wide.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  console.log('Проверено: итоги, поиск, копия без факта, создание и редактирование строки, массовый архив/восстановление, ФОТ, темы, телефон и широкий экран.');
}
